import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import ts from 'typescript';
const mod = { exports: {} };
const source = ts.transpileModule(fsSync.readFileSync('lib/project-directory.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
vm.runInNewContext(source, { module: mod, exports: mod.exports, console, Map, Set, crypto });
const lib=mod.exports;
await fs.mkdir('work',{recursive:true});
const root=await fs.mkdtemp(path.resolve('work/project-directory-test-'));
const good={ format:'pocket-atlas-project-v1', name:'同名项目', projectNotes:'备注', raw:'smiles\nCCO', mapping:{smiles:'smiles'}, selected:[], excluded:[], notes:{}, threshold:.6, moleculeCount:1 };
function handle(name,fail=false){const target=path.join(root,name);return {kind:'file',name,async getFile(){const stat=await fs.stat(target);return {lastModified:stat.mtimeMs,size:stat.size,text:()=>fs.readFile(target,'utf8')};},async createWritable(){let buffer;return {async write(s){if(fail)throw Error('模拟磁盘写入失败');buffer=s;},async close(){await fs.writeFile(target+'.pending',buffer);await fs.rename(target+'.pending',target);},async abort(){}};}};}
await fs.writeFile(path.join(root,'one.json'),JSON.stringify(good));
await fs.writeFile(path.join(root,'two.json'),JSON.stringify(good));
await fs.writeFile(path.join(root,'broken.json'),'{bad');
await fs.writeFile(path.join(root,'unrelated.json'),'{}');
await fs.writeFile(path.join(root,'ignore.txt'),'text');
const dir={queryPermission:async()=> 'granted',async *values(){for(const name of await fs.readdir(root))yield handle(name);}};
const scan=await lib.scanProjects(dir);
assert.equal(scan.entries.length,2);assert.equal(scan.warnings.length,2);assert.notEqual(scan.entries[0].id,scan.entries[1].id);
const h=handle('one.json');const f=await h.getFile();const stamp=`${f.lastModified}:${f.size}`;
const saved=await lib.writeProjectFile(h,{...good,projectNotes:'修改备注'},stamp);
assert.equal(JSON.parse(await fs.readFile(path.join(root,'one.json'),'utf8')).projectNotes,'修改备注');
await fs.writeFile(path.join(root,'one.json'),JSON.stringify({...good,name:'外部编辑的项目，不可覆盖'}));
await assert.rejects(lib.writeProjectFile(h,good,saved),/其他窗口/);
const before=await fs.readFile(path.join(root,'one.json'),'utf8');
await assert.rejects(lib.writeProjectFile(handle('one.json',true),good),/模拟磁盘/);
assert.equal(await fs.readFile(path.join(root,'one.json'),'utf8'),before);
await assert.rejects(lib.scanProjects({...dir,queryPermission:async()=> 'denied'}),/重新授权/);
assert.throws(()=>lib.validateProjectDocument({format:'pocket-atlas-project-v1'}),/有效/);
console.log('Project file tests passed: scanning, invalid JSON isolation, duplicate names, note updates, external-change protection, failed-write preservation, revoked permissions.');
console.log('Fixtures retained in ignored '+root);
